# Запуск:
#   blender.exe --background --factory-startup --python tools/make_circle2_props.py -- assets/models
#
# --factory-startup обязателен: чужие аддоны в пользовательском профиле лезут в
# glTF-экспорт и добавляют в файл то, чего мы не просили.
#
# Геометрические помощники и договорённости с игрой — в blender_prop_kit.py.
# После генерации обязательно:
#   godot_console.exe --headless --path C:\Комната --import
# иначе preload падает с «no resource loaders».
#
# Замысел круга — в КРУГ_II.md. Коротко: вещи здесь чужие и парные. Ни одной
# откровенности, всё намёками — две щётки, два бокала, чьё-то платье.

import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from blender_prop_kit import COLORS, Prop, run

# Цвета нужны только чтобы .glb можно было открыть и увидеть предмет: в игре
# материалы подменяются палитрой сцены по имени.
COLORS.update({
    "paper": (0.80, 0.76, 0.66, 1.0),
    "ribbon": (0.44, 0.20, 0.20, 1.0),
    "leather": (0.26, 0.15, 0.11, 1.0),
    "fabric": (0.40, 0.26, 0.30, 1.0),
    "handle": (0.78, 0.74, 0.68, 1.0),
})


def letter_sheet():
    """Одинокий лист, лежащий на полу. Ставится через MultiMesh с разным поворотом.

    Плоскость чуть выше нуля: вплотную к полу она мерцает.
    """
    prop = Prop("c2_letter_sheet")
    prop.plate([(-0.105, -0.074), (0.105, -0.074), (0.105, 0.074), (-0.105, 0.074)],
               0.0, 0.0015, "paper")
    # Загнувшийся угол: лист не лежит идеально, его носило ветром.
    prop.plate([(0.062, 0.046), (0.105, 0.074), (0.058, 0.074)],
               0.0015, 0.006, "paper")
    return prop


def letter_bundle():
    """Связка писем, перехваченная лентой. Начало координат — низ по центру."""
    prop = Prop("c2_letter_bundle")
    for step in range(6):
        # Каждый лист чуть повёрнут: связку перевязывали не аккуратно.
        prop.box((0.004 * step - 0.010, 0.003 * step - 0.008, 0.004 + 0.007 * step),
                 (0.208, 0.148, 0.007), "paper")
    prop.box((0.0, 0.0, 0.024), (0.030, 0.156, 0.052), "ribbon")
    prop.box((0.0, 0.0, 0.024), (0.216, 0.028, 0.052), "ribbon")
    return prop


def suitcase():
    """Чужой чемодан: не твой и стоит не там, где ты бы поставил."""
    prop = Prop("c2_suitcase")
    prop.box((0.0, 0.0, 0.185), (0.520, 0.200, 0.370), "leather")
    # Шов крышки и два замка.
    prop.box((0.0, 0.0, 0.250), (0.528, 0.208, 0.014), "brass")
    for dx in (-0.150, 0.150):
        prop.box((dx, -0.104, 0.250), (0.062, 0.020, 0.044), "brass")
    # Уголки по низу: чемодан ставили много раз.
    for dx in (-0.245, 0.245):
        for dy in (-0.092, 0.092):
            prop.box((dx, dy, 0.014), (0.044, 0.044, 0.028), "brass")
    # Ручка: две стойки и перекладина.
    for dx in (-0.070, 0.070):
        prop.box((dx, 0.0, 0.388), (0.016, 0.018, 0.036), "brass")
    prop.box((0.0, 0.0, 0.404), (0.156, 0.026, 0.018), "handle")
    return prop


def wine_set():
    """Бутылка и два бокала на подносе. Оба бокала использованы."""
    prop = Prop("c2_wine_set")
    prop.box((0.0, 0.0, 0.010), (0.300, 0.220, 0.020), "brass")
    prop.lathe([(0.0, 0.020), (0.038, 0.020), (0.038, 0.150), (0.020, 0.198),
                (0.016, 0.290), (0.0, 0.296)], "glass", center=(-0.088, 0.0), segments=12)
    for dx, dy in ((0.058, -0.048), (0.070, 0.052)):
        prop.lathe([(0.0, 0.020), (0.036, 0.020), (0.036, 0.026), (0.006, 0.034),
                    (0.006, 0.088), (0.034, 0.128), (0.040, 0.186), (0.038, 0.188),
                    (0.032, 0.130), (0.004, 0.092), (0.004, 0.030), (0.0, 0.026)],
                   "glass", center=(dx, dy), segments=12)
    return prop


def toothbrush_glass():
    """Стакан с двумя щётками. Самая тихая вещь круга и самая говорящая."""
    prop = Prop("c2_toothbrush_glass")
    prop.lathe([(0.0, 0.0), (0.034, 0.0), (0.034, 0.004), (0.030, 0.008),
                (0.030, 0.092), (0.034, 0.096), (0.034, 0.100), (0.0, 0.100)],
               "glass", segments=14)
    for dx, tilt in ((-0.011, -0.16), (0.012, 0.19)):
        prop.box((dx, 0.0, 0.104), (0.010, 0.014, 0.170), "handle", rot_y=tilt)
    return prop


def dress_hanger():
    """Платье на вешалке. Висит вниз от точки крепления, как плечики на штанге."""
    prop = Prop("c2_dress_hanger")
    # Крюк: две коротких перекладины вместо дуги — на такой мелочи её не видно.
    prop.box((0.0, 0.0, -0.014), (0.008, 0.008, 0.028), "brass")
    prop.box((0.014, 0.0, -0.030), (0.028, 0.008, 0.008), "brass")
    # Плечики.
    prop.box((0.0, 0.0, -0.048), (0.008, 0.008, 0.028), "brass")
    for side in (-1.0, 1.0):
        prop.box((side * 0.088, 0.0, -0.070), (0.180, 0.014, 0.014), "brass", rot_y=side * 0.16)
    prop.box((0.0, 0.0, -0.090), (0.330, 0.012, 0.012), "brass")
    # Платье: несколько поперечин, расширяющихся вниз.
    widths = [(0.300, -0.150, 0.120), (0.330, -0.290, 0.160), (0.380, -0.450, 0.200),
              (0.430, -0.610, 0.180)]
    for width, height, depth in widths:
        prop.box((0.0, 0.0, height), (width, depth * 0.30, abs(height) * 0.42), "fabric")
    return prop


def vent_grille():
    """Вентиляционная решётка — один из четырёх источников сквозняка.

    Настенная: начало координат — низ по центру на плоскости стены, свес в -Y.
    """
    prop = Prop("c2_vent_grille")
    width, height = 0.280, 0.200
    prop.box((0.0, -0.008, height - 0.010), (width, 0.016, 0.020), "metal")
    prop.box((0.0, -0.008, 0.010), (width, 0.016, 0.020), "metal")
    for side in (-1.0, 1.0):
        prop.box((side * (width / 2.0 - 0.010), -0.008, height / 2.0),
                 (0.020, 0.016, height), "metal")
    # Наклонные ламели: сквозь них видно темноту шахты.
    for step in range(5):
        prop.box((0.0, -0.014, 0.036 + 0.032 * step), (width - 0.036, 0.022, 0.014),
                 "brass", rot_y=0.0)
    return prop


def window_catch():
    """Латунный шпингалет: единственный носимый предмет первого акта."""
    prop = Prop("c2_window_catch")
    prop.box((0.0, 0.0, 0.006), (0.104, 0.032, 0.012), "brass")
    for dx in (-0.036, 0.036):
        prop.lathe([(0.0, 0.012), (0.007, 0.012), (0.007, 0.019), (0.0, 0.019)],
                   "brass", center=(dx, 0.0), segments=8)
    # Рычажок, отведённый в сторону: шпингалет снят, а не закрыт.
    prop.box((0.014, 0.0, 0.026), (0.086, 0.014, 0.014), "brass", rot_y=0.28)
    prop.lathe([(0.0, 0.026), (0.011, 0.026), (0.011, 0.038), (0.0, 0.038)],
               "handle", center=(0.052, 0.0), segments=10)
    return prop


run({
    "c2_letter_sheet.glb": letter_sheet,
    "c2_letter_bundle.glb": letter_bundle,
    "c2_suitcase.glb": suitcase,
    "c2_wine_set.glb": wine_set,
    "c2_toothbrush_glass.glb": toothbrush_glass,
    "c2_dress_hanger.glb": dress_hanger,
    "c2_vent_grille.glb": vent_grille,
    "c2_window_catch.glb": window_catch,
})
